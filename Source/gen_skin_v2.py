def esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def place(panels, wip):
    """Compute every control/legend rect. Returns list of element dicts."""
    out = []
    for p in panels:
        colw_default = p.get("colw", CELL_W)
        # Grid origin: centred in the panel unless the panel is left aligned
        if p.get("align") == "left" or p["ncols"] is None:
            gx = p["x"] + 32
        else:
            gx = p["x"] + (p["w"] - p["ncols"] * colw_default) // 2
        gy = p["y"] + TITLE_H + TOP_PAD

        for key, label, shlab, col, row, span, sub in p["items"]:
            tag, attrs = wip[key]
            kind = tag
            # Pitch envelope mixes one knob column with fader columns
            if p["name"] == "PITCH ENVELOPE":
                cx = gx if col == 0 else gx + CELL_W + (col - 1) * FADER_W
                cw = CELL_W if col == 0 else FADER_W
            else:
                cx = gx + int(round(col * colw_default))
                cw = int(round((span or 1) * colw_default))
            cy = gy + row * ROW_H
            e = dict(key=key, tag=tag, attrs=attrs, views=p["views"],
                     panel=p["name"], label=label, shift=shlab)

            if kind == "knob":
                e["rect"] = (cx + (cw - KNOB) // 2, cy + KNOB_DY, KNOB, KNOB)
                e["lrect"] = (cx, cy, cw, "center")
            elif kind == "combo":
                ly = cy + (sub or 0) * COMBO_STEP
                e["rect"] = (cx + COMBO_PAD, ly + LEGEND_H, cw - 2 * COMBO_PAD, COMBO_H)
                e["lrect"] = (cx + COMBO_PAD, ly, cw - 2 * COMBO_PAD, "left")
            elif kind == "toggle":
                e["rect"] = (cx + (cw - TOGGLE_W) // 2, cy + LEGEND_H + 8,
                             TOGGLE_W, TOGGLE_H)
                e["lrect"] = (cx, cy, cw, "center")
            elif kind == "fader":
                top = cy + LEGEND_H + 8
                h = p["y"] + p["h"] - 36 - top
                e["rect"] = (cx + (cw - FADER_TRACK_W) // 2, top, FADER_TRACK_W, h)
                e["lrect"] = (cx, cy, cw, "center")
            elif kind in ("stepgrid", "bassgrid"):
                top = cy - 20
                e["rect"] = (p["x"] + 32, top, p["w"] - 64, p["y"] + p["h"] - 28 - top)
                e["lrect"] = None
            out.append(e)
    return out


