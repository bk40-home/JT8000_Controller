#!/usr/bin/env python3
"""
gen_skin_v2.py - JT-8000 skin v2 generator (single source of geometry).

WHY THIS EXISTS
---------------
The WIP skin was hand-placed in the layout editor, so every panel, legend and
control carried its own free-floating coordinates. Small differences (a box
4 dp short here, a legend 2 dp lower there) add up to the "borders shift" and
"nothing lines up" look. This script places everything on ONE grid, from ONE
table, and emits every output from that table so nothing can drift:

    jt8000.rml      - same element grammar as before; every control keeps its
                      exact class / param / key / default / options / index
                      attributes (copied verbatim from the WIP file). Only the
                      `style` (position + size) and legend TEXT change.
    jt8000_v2.rcss  - a SMALL override sheet linked AFTER the existing
                      jt8000.rcss. It never sets `display`, so the view
                      switching (v-main / v-reverb ...) is untouched.
    bg_v2.png       - plain chassis + header artwork painted from the same
                      coordinates as the header hit areas.

FUNCTIONAL CONTRACT (checked by verify() at the end):
    * the set of controls and every binding attribute is identical to the WIP
    * no two controls that can be visible together overlap
    * every control sits inside its panel

Usage:  python3 gen_skin_v2.py <wip.rml> <outdir>
"""

