def st(x, y, w, h=None, extra=""):
    s = "left:%ddp; top:%ddp; width:%ddp;" % (x, y, w)
    if h is not None:
        s += " height:%ddp;" % h
    return s + extra


def emit_rml(panels, elems):
    L = ['<rml>', '<head>', '\t<title>JT-8000</title>',
         '\t<link type="text/rcss" href="jt8000.rcss"/>',
         '\t<!-- v2 override sheet: delete this line to roll back the look -->',
         '\t<link type="text/rcss" href="jt8000_v2.rcss"/>',
         '</head>', '<body class="main">', '',
         '\t<!-- Generated by gen_skin_v2.py - edit the table there, not here. -->',
         '\t<div class="band"/>', '']

    # ---- header ----
    lx, ly, lw, lh = LCD
    L.append('\t<!-- Header: LCD -->')
    L.append('\t<div class="lcd1" id="lcd1" style="%s">INIT PATCH</div>'
             % st(lx + 32, LCD1_TOP, 700, LCD1_H, " text-align:left;"))
    L.append('\t<div class="lcd2" id="lcd2" style="%s"></div>'
             % st(lx + 32, LCD2_TOP, lw - 64, LCD2_H, " text-align:left;"))
    for i in range(8):
        L.append('\t<div class="voice" id="voice%d" style="%s"/>'
                 % (i, st(lx + lw - 32 - 8 * 34 + 12 + i * 34, ly + 30, 22, 22)))
    L.append('')
    L.append('\t<!-- Header: lit plate (under), caption, then transparent hit area (on top) -->')
    for i, (tag, cap, btncls, vcls) in enumerate(LAYERS):
        x = BTN_X0 + i * (BTN_W + BTN_GAP)
        L.append('\t<div class="layerlit %s" style="%s"/>' % (vcls, st(x, BTN_Y[1], BTN_W, BTN_H)))
    for i, (act, cap) in enumerate(ACTIONS):
        x = BTN_X0 + i * (BTN_W + BTN_GAP)
        L.append('\t<div class="btncap" style="%s">%s</div>'
                 % (st(x, BTN_Y[0], BTN_W, BTN_H, " line-height:%ddp; text-align:center;" % BTN_H), cap))
    for i, (tag, cap, btncls, vcls) in enumerate(LAYERS):
        x = BTN_X0 + i * (BTN_W + BTN_GAP)
        L.append('\t<div class="btncap %s" style="%s">%s</div>'
                 % (btncls, st(x, BTN_Y[1], BTN_W, BTN_H, " line-height:%ddp; text-align:center;" % BTN_H), cap))
    sx, sy, sw, sh = SHIFT
    L.append('\t<div class="btncap shiftcap" style="%s">SHIFT</div>'
             % st(sx, sy, sw, sh, " line-height:%ddp; text-align:center;" % sh))
    for i, (act, cap) in enumerate(ACTIONS):
        x = BTN_X0 + i * (BTN_W + BTN_GAP)
        L.append('\t<div class="actionbtn" data-action="%s" style="%s"/>' % (act, st(x, BTN_Y[0], BTN_W, BTN_H)))
    for i, (tag, cap, btncls, vcls) in enumerate(LAYERS):
        x = BTN_X0 + i * (BTN_W + BTN_GAP)
        L.append('\t<div class="layerbtn" data-layer="%s" style="%s"/>' % (tag, st(x, BTN_Y[1], BTN_W, BTN_H)))
    L.append('\t<div class="shiftbtn" style="%s"/>' % st(sx, sy, sw, sh))
    L.append('')

    # ---- panel boxes first so they paint underneath everything ----
    L.append('\t<!-- Panel frames -->')
    for p in panels:
        L.append('\t<div class="secbox %s" style="%s"/>' % (p["views"], st(p["x"], p["y"], p["w"], p["h"])))
    L.append('')

    # ---- per panel: title, legends, controls ----
    for p in panels:
        L.append('\t<!-- %s -->' % p["name"].title())
        L.append('\t<div class="sectitle %s" style="%s">%s</div>'
                 % (p["views"], st(p["x"], p["y"], p["w"] - 18 - 6, extra=" text-align:left;"), esc(p["name"])))
        for e in elems:
            if e["panel"] != p["name"]:
                continue
            ctrl_views = " ".join(e["attrs"]["class"].split()[1:])
            if e["lrect"] is not None:
                lx_, ly_, lw_, al = e["lrect"]
                lst = st(lx_, ly_, lw_, extra=" text-align:%s;" % al)
                if e["shift"]:
                    prim = " ".join(v for v in ctrl_views.split() if v != "v-shift")
                    L.append('\t<div class="legend %s" style="%s">%s</div>' % (prim, lst, esc(e["label"])))
                    L.append('\t<div class="legend shiftalt v-shift" style="%s">%s</div>' % (lst, esc(e["shift"])))
                else:
                    L.append('\t<div class="legend %s" style="%s">%s</div>' % (ctrl_views, lst, esc(e["label"])))
            x, y, w, h = e["rect"]
            attrs = " ".join('%s="%s"' % kv for kv in e["attrs"].items())
            style = st(x, y, w, h)
            if e["tag"] == "fader":
                L.append('\t<fader %s style="%s">' % (attrs, style))
                L.append('\t\t<div class="thumb"/>')
                L.append('\t</fader>')
            else:
                L.append('\t<%s %s style="%s"/>' % (e["tag"], attrs, style))
        # Panel action buttons: an .actionbtn (so JtRmlComponent routes the
        # click through onAction) that carries its own caption.  Placed on the
        # same cell grid as the controls; visibility via the panel's views.
        gx, gy = p["x"] + 32, p["y"] + TITLE_H + TOP_PAD
        for a in p.get("actions", []):
            act, cap, col, row, span = a[:5]
            slot = a[5] if len(a) > 5 else None
            bx = gx + int(round(col * CELL_W)) + 8
            # slot None: one button under a legend line (like a toggle);
            # slot k: stacked buttons filling the cell, no legend.
            if slot is None:
                by = gy + row * ROW_H + LEGEND_H + 8
            else:
                by = gy + row * ROW_H + 8 + slot * (ACTION_BTN_H + 16)
            bw = int(round(span * CELL_W)) - 16
            L.append('\t<div class="actionbtn bassbtn %s" data-action="%s" style="%s">%s</div>'
                     % (p["views"], act,
                        st(bx, by, bw, ACTION_BTN_H,
                           " line-height:%ddp; text-align:center;" % ACTION_BTN_H),
                        esc(cap)))
        L.append('')

    L.append('</body>')
    L.append('</rml>')
    return "\n".join(L) + "\n"


