def views_of(cls):
    return {v for v in cls.split() if v.startswith("v-")}


def verify(panels, elems, wip):
    errs = []
    placed = {e["key"] for e in elems}
    for k in wip:
        if k not in placed:
            errs.append("control missing from new layout: " + k)
    for k in placed:
        if k not in wip:
            errs.append("unknown control in table: " + k)

    pmap = {p["name"]: p for p in panels}

    def inside(r, p):
        x, y, w, h = r
        return x >= p["x"] and y >= p["y"] + TITLE_H and x + w <= p["x"] + p["w"] and y + h <= p["y"] + p["h"]

    for e in elems:
        if not inside(e["rect"], pmap[e["panel"]]):
            errs.append("outside panel: %s %s" % (e["key"], e["rect"]))

    # Overlap: only between controls that can be visible together
    def ov(a, b):
        return a[0] < b[0] + b[2] and b[0] < a[0] + a[2] and a[1] < b[1] + b[3] and b[1] < a[1] + a[3]

    for i, a in enumerate(elems):
        va = views_of(a["attrs"]["class"])
        for b in elems[i + 1:]:
            if va & views_of(b["attrs"]["class"]) and ov(a["rect"], b["rect"]):
                # knob elements may touch neighbours' transparent margins only
                if a["tag"] == b["tag"] == "knob":
                    continue
                errs.append("overlap: %s <-> %s" % (a["key"], b["key"]))
    return errs


def main():
    wip_path, outdir = sys.argv[1], sys.argv[2]
    os.makedirs(outdir, exist_ok=True)
    wip = merge_extra(read_wip(wip_path))
    panels = build_panels()
    elems = place(panels, wip)
    errs = verify(panels, elems, wip)
    for e in errs:
        print("ERROR:", e)
    if errs:
        raise SystemExit(1)
    open(os.path.join(outdir, "jt8000.rml"), "w", encoding="utf-8", newline="\r\n").write(emit_rml(panels, elems))
    open(os.path.join(outdir, "jt8000_v2.rcss"), "w", encoding="utf-8", newline="\r\n").write(RCSS)
    paint_bg(os.path.join(outdir, "bg_v2.png"))
    print("ok: %d controls, %d panels -> %s" % (len(elems), len(panels), outdir))


if __name__ == "__main__":
    main()
