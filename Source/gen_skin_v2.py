def env_items(prefix, with_depth):
    items, c0 = [], 0
    if with_depth:
        items.append((prefix + ".depth", "DEPTH", None, 0, 0, 1, None))
        c0 = 1
    for i, (p, lab, sh) in enumerate([("attack", "ATT", "A CRV"),
                                      ("decay", "DEC", "D CRV"),
                                      ("sustain", "SUS", None),
                                      ("release", "REL", "R CRV")]):
        items.append((prefix + "." + p, lab, sh, c0 + i, 0, 1, None))
    return items


