def merge_extra(ctrls):
    """Add EXTRA_CTRLS that the WIP does not already define."""
    for key, (tag, cls, default, options) in EXTRA_CTRLS.items():
        if key in ctrls:
            continue
        if tag == "bassgrid":
            a = OrderedDict([("class", cls), ("param", ""), ("key", key), ("steps", "32")])
            ctrls[key] = (tag, a)
            continue
        a = OrderedDict([("class", cls), ("param", key), ("key", key), ("default", default)])
        if options is not None:
            a["options"] = options
            a["index"] = "0"
        ctrls[key] = (tag, a)
    return ctrls


def read_wip(path):
    """Return {key: (tag, OrderedDict attrs-without-style)} from the WIP RML."""
    text = open(path, encoding="utf-8").read()
    ctrls = OrderedDict()
    for m in CTRL_RE.finditer(text):
        tag, body = m.group(1), m.group(2)
        attrs = OrderedDict(ATTR_RE.findall(body))
        attrs.pop("style", None)
        key = attrs["key"]
        if key in ctrls:
            raise SystemExit("duplicate key in WIP: " + key)
        ctrls[key] = (tag, attrs)
    return ctrls


