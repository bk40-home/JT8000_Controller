# square of side min(w,h) - 2*6 logical px centred in the strip. Fixing the
# heights makes the dial position a known number, so the bay is painted there.
LCD1_TOP, LCD1_H = 66, 72
LCD2_TOP, LCD2_H = 146, 44


def encoder_centre():
    """Mirror of positionEncoderStrip() + JtEncoderStrip::resized(), in dp."""
    top, bot = LCD1_TOP, LCD2_TOP + LCD2_H
    h = bot - top
    strip_w = 1.8 * h
    gap = h / 6.0
    x = (LCD[0] + 32) - strip_w - gap          # lcd1.left = LCD x + 32
    return (round(x + strip_w / 2), round(top + h / 2))


