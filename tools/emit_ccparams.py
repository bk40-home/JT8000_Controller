#!/usr/bin/env python3
# =============================================================================
# emit_ccparams.py — generate the CCParam rows the plugin is missing
# -----------------------------------------------------------------------------
# WHY THIS IS A SUPPLEMENT AND NOT A REPLACEMENT
#   The plugin builds its APVTS from kAllParams[] in CCDefinitions.h, which is
#   hand-authored and 143 rows deep, carrying per-choice CC lookup tables, an
#   isLocalOnly flag whose meaning has drifted, and int-lattice bounds. Emitting
#   the whole table would mean reproducing all of that and re-verifying 143 rows
#   that currently work.
#
#   So this emits ONLY the rows that are absent - the 18 parameters that exist
#   in the firmware and have never had an APVTS entry - as an include file that
#   drops inside the existing array. Every existing row is untouched, and the
#   diff a human has to review is the section enum plus two lines.
#
#   It is a bridge, not the destination: when kAllParams is eventually generated
#   whole, this file goes away.
#
# WHAT IS MISSING AND WHY
#   The entire arpeggiator (13) and the sequencer's aux lane (5). They were
#   added to params.yaml and to the firmware, and the ESP32 controller picked
#   them up because its ParamTable.h IS generated. The plugin did not, because
#   its table is not. That is the whole story of the drift.
#
# REQUIRES
#   params.yaml seeded with `v1_cc` (see seed_ids.py).
#
# USAGE
#   python3 emit_ccparams.py > JtParamsMissing.h
# =============================================================================

import os
import sys

# Parameters the plugin already has. Anything in params.yaml but not here needs
# a row emitting. Derived from CCDefinitions.h at the time of writing; the
# script re-derives it if the header is given.
# The arpeggiator landed in CCDefinitions.h in the meantime, and both grids
# absorb their own step parameters, so only the sequencer's aux lane is left.
MISSING_PREFIXES = ("seq.aux_",)
ALSO_MISSING = set()

# Section enum name per key prefix. STEP_SEQ already exists; ARPEGGIATOR is new
# and must be added to the enum by hand - see the patch note at the end.
SECTION_FOR = {
    "arp.": "Section::ARPEGGIATOR",
    "seq.": "Section::STEP_SEQ",
}

# params.yaml option set -> the existing name array in CCDefinitions.h. Reusing
# them avoids a second copy of the same strings drifting out of step.
OPTION_ARRAY = {
    "timing_mode":  ("kTimingNames", 12),
    "seq_aux_dest": ("kSeqAuxDestNames", 5),
    "on_off":       ("kOnOffNames", 2),
}


def section_for(key):
    for pre, sec in SECTION_FOR.items():
        if key.startswith(pre):
            return sec
    return "Section::STEP_SEQ"


def cpp_str(s):
    return '"' + str(s).replace('"', '\\"') + '"'


def default_byte(p, opts):
    """CCParam.defVal is a CC byte for knobs but a choice INDEX for combos and
    toggles. Getting that wrong shows up as a control that boots to the wrong
    position, which is easy to miss and annoying to chase."""
    d = p.get("default", 0)
    if p["type"] in ("select", "toggle"):
        return int(d)
    if p["type"] == "int":
        return int(d)
    rng = p.get("range") or {}
    lo, hi = float(rng.get("min", 0.0)), float(rng.get("max", 1.0))
    if hi <= lo:
        return 0
    return int(round((float(d) - lo) / (hi - lo) * 127.0))


def emit(doc, option_sets, used_ccs=None, rows_only=False, names_only=False):
    """`used_ccs` is the CC set already present in kAllParams. A collision would
    give two rows the same CC, and the first match wins wherever the table is
    searched by CC - a silent, extremely confusing failure."""
    params = [p for p in doc["params"]
              if p["key"].startswith(MISSING_PREFIXES)
              or p["key"] in ALSO_MISSING]

    if used_ccs:
        clash = [(p["key"], p["v1_cc"]) for p in params
                 if int(p.get("v1_cc", -1)) in used_ccs]
        if clash:
            raise SystemExit("ABORT: CC already used by kAllParams: %s" % clash)

    L = []
    a = L.append
    a("// " + "=" * 74)
    a("// JtParamsMissing.h — GENERATED by tools/emit_ccparams.py")
    a("// " + "=" * 74)
    a("// The %d parameters that exist in params.yaml and the firmware but have"
      % len(params))
    a("// never had an APVTS entry: the arpeggiator and the sequencer's aux")
    a("// lane. Included inside kAllParams[] in CCDefinitions.h.")
    a("//")
    a("// Every id here is new, so nothing already saved is affected. The CC")
    a("// numbers come from params.yaml's v1_cc and sit above the existing range")
    a("// (204+), where they cannot be confused with a MIDI controller number.")
    a("// " + "=" * 74)
    a("")

    # Option arrays needed but not already present.
    need = {}
    for p in params:
        o = p.get("options")
        if o and o not in OPTION_ARRAY:
            need[o] = option_sets[o]
    for name, opts in sorted(need.items()):
        ident = "kArp" + "".join(w.capitalize() for w in name.split("_"))
        OPTION_ARRAY[name] = (ident, len(opts))
        if not rows_only:
            a("static const char* const %s[] = { %s };"
              % (ident, ",".join(cpp_str(o) for o in opts)))
    if need and not rows_only:
        a("")
    if names_only:
        return "\n".join(L) + "\n"

    for p in params:
        key = p["key"]
        opts = p.get("options")
        style_field = "KNOB"

        if p["type"] == "select":
            arr, n = OPTION_ARRAY[opts]
            style_field = "COMBO(%s, %d)" % (arr, n)
        elif p["type"] == "toggle":
            style_field = "TOGGLE(kOnOffNames, 2)"

        extra = ""
        if p["type"] == "int":
            rng = p.get("range") or {}
            extra = ", %d, %d" % (int(rng.get("min", 0)), int(rng.get("max", 127)))

        a("    { %-4s %-22s %-24s %-24s %-5s %-28s false%s },   // %s"
          % (str(int(p["v1_cc"]) if "v1_cc" in p else 0) + ",",
             cpp_str(p["juce_id"]) + ",",
             cpp_str(p["name"]) + ",",
             section_for(key) + ",",
             str(default_byte(p, option_sets)) + ",",
             style_field + ",",
             extra,
             key))

    if rows_only:
        return "\n".join(L) + "\n"

    a("")
    a("// " + "-" * 74)
    a("// TO USE")
    a("//   1. Add ARPEGGIATOR to `enum class Section` before PERFORMANCE_GLOBAL,")
    a("//      and \"Arpeggiator\" to sectionNames[] in the matching position.")
    a("//   2. Inside kAllParams[], before the closing brace:")
    a("//          #include \"JtParamsMissing.h\"")
    a("//   3. Rebuild. kNumParams grows by %d automatically if it is a" % len(params))
    a("//      sizeof/sizeof expression; check it is, and not a literal.")
    a("// " + "-" * 74)
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from gen_params import build_model
    doc = build_model()

    used = None
    if len(sys.argv) > 1:                      # optional CCDefinitions.h path
        import re
        blk = open(sys.argv[1], encoding="utf-8", errors="replace").read()
        blk = blk[blk.index("static const CCParam kAllParams[] ="):]
        used = {int(m.group(1))
                for m in re.finditer(r'\{\s*(-?\d+)\s*,\s*"[a-z0-9_]+"', blk)}
    # Two files: the option arrays must be DECLARED before kAllParams, while
    # the rows go INSIDE it. One file cannot be both.
    names = emit(doc, doc["option_sets"], used, names_only=True)
    rows  = emit(doc, doc["option_sets"], used, rows_only=True)

    out_dir = os.path.dirname(sys.argv[2]) if len(sys.argv) > 2 else "."
    with open(os.path.join(out_dir, "JtParamsMissingNames.h"), "w",
              encoding="utf-8", newline="\r\n") as f:
        f.write(names)
    with open(os.path.join(out_dir, "JtParamsMissingRows.h"), "w",
              encoding="utf-8", newline="\r\n") as f:
        f.write(rows)
    sys.stderr.write("JtParamsMissingNames.h  — include ABOVE kAllParams\n"
                     "JtParamsMissingRows.h   — include INSIDE kAllParams\n")
