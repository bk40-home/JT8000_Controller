#!/usr/bin/env python3
# =============================================================================
# emit_juce.py — the JUCE emitter gen_params.py always planned for
# -----------------------------------------------------------------------------
# gen_params.py's own header states the intent:
#
#     "the ESP32 and JUCE emitters are added in Phase 5 and will reuse the same
#      loaded/validated model (build_model())"
#
# The Teensy and docs emitters exist; this one never got written, and that is
# precisely why the plugin drifted. CCDefinitions.h is hand-authored, so:
#
#     * 18 parameters that exist in the firmware have NO APVTS entry at all -
#       the whole arpeggiator, the sequencer's aux lane and step value. The
#       plugin has never been able to reach them.
#     * usb_return_level exists in the plugin with no params.yaml key.
#     * the names diverged so far that only 26 of 160 map by substitution.
#
# This emitter closes that seam the same way the Teensy one did: params.yaml
# becomes the single source, and drift stops being possible rather than merely
# being detected.
#
# WIRING IT IN
#   Drop this beside gen_params.py and add two lines to its main():
#
#       from emit_juce import emit_juce, JUCE_PATH
#       ok &= write_if_changed(JUCE_PATH, emit_juce(doc), args.check)
#
#   It reuses build_model(), so every validation gen_params.py performs already
#   applies - unique ids, sane ranges, valid defaults, option sets that exist.
#
# WHAT IT DOES NOT DO
#   It does not emit the CC bindings. Those live in JtBridgeTable.h, which is
#   still hand-maintained despite its "GENERATED" banner; folding v1 CC numbers
#   into params.yaml is a separate job and a bigger one, because the CC space
#   has its own uniqueness and RESERVED-range rules.
# =============================================================================

import os

JUCE_PATH = os.path.join("gen", "JtParamTable.h")

# Widget hint for the plugin. Mirrors the panel generator's classification so a
# parameter cannot be a combo in one place and a knob in the other.
def widget_of(p):
    t = p["type"]
    if t == "select":
        return "Widget::Combo"
    if t == "toggle":
        return "Widget::Toggle"
    if p.get("widget") == "envelope":
        return "Widget::Fader"
    return "Widget::Knob"


def cpp_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def cpp_float(x):
    v = float(x)
    if v == int(v) and abs(v) < 1e15:
        return f"{int(v)}.0f"
    return f"{v!r}f"


def emit_juce(doc):
    """Return the contents of gen/JtParamTable.h."""
    params = doc["params"]
    option_sets = doc["option_sets"]
    sections = doc["sections"]

    L = []
    a = L.append

    a("// " + "=" * 75)
    a("// JtParamTable.h — GENERATED by tools/gen_params.py.  DO NOT HAND-EDIT.")
    a("// " + "=" * 75)
    a("// APVTS parameter definitions for the JUCE plugin, generated from")
    a("// params.yaml so the plugin cannot drift from the firmware.")
    a("//")
    a("// `juceId` is PERSISTED: it appears in saved patches, host automation and")
    a("// every project that has loaded the plugin. It is carried in params.yaml")
    a("// rather than derived from the key, so existing ids stay byte-identical")
    a("// and nothing already saved breaks.")
    a("//")
    a("// Ranges are the firmware's own. A value is stored NORMALISED in the")
    a("// APVTS and converted by these ranges, so the plugin and the engine")
    a("// cannot disagree about what 0.5 means.")
    a("// " + "=" * 75)
    a("#pragma once")
    a("")
    a("#include <cstdint>")
    a("")
    a("namespace JtParams {")
    a("")
    a("enum class Widget : uint8_t { Knob, Fader, Combo, Toggle };")
    a("enum class Curve  : uint8_t { Lin, Log, Seg2 };")
    a("enum class Scope  : uint8_t { Patch, Performance, Global };")
    a("")
    a("struct Option { const char* name; };")
    a("")
    a("struct Param")
    a("{")
    a("    uint16_t    paramId;      // 14-bit v2 ParamID, matches the firmware")
    a("    const char* key;          // dotted key, params.yaml")
    a("    const char* juceId;       // APVTS id — persisted, never re-derive")
    a("    const char* name;         // host-visible name")
    a("    const char* label;        // short panel legend")
    a("    Widget      widget;")
    a("    Scope       scope;")
    a("    Curve       curve;")
    a("    float       min;")
    a("    float       max;")
    a("    float       mid;          // seg2 breakpoint, else 0")
    a("    float       def;")
    a("    const char* unit;")
    a("    bool        bipolar;")
    a("    const Option* options;    // null unless widget == Combo")
    a("    uint8_t     optionCount;")
    a("    uint8_t     section;")
    a("};")
    a("")

    # --- option sets --------------------------------------------------------
    a("// " + "-" * 75)
    a("// Option sets")
    a("// " + "-" * 75)
    used = sorted({p["options"] for p in params if p.get("options")})
    for name in used:
        ident = "kOpt_" + name
        opts = option_sets[name]
        a(f"static constexpr Option {ident}[] = {{")
        for o in opts:
            a(f"    {{ {cpp_str(o)} }},")
        a("};")
    a("")

    # --- parameters ---------------------------------------------------------
    a("// " + "-" * 75)
    a(f"// Parameters ({len(params)})")
    a("// " + "-" * 75)
    a(f"static constexpr int kNumParams = {len(params)};")
    a("")
    a("static constexpr Param kParams[kNumParams] = {")

    curve_map = {"lin": "Curve::Lin", "log": "Curve::Log", "seg2": "Curve::Seg2"}
    scope_map = {"patch": "Scope::Patch", "performance": "Scope::Performance",
                 "global": "Scope::Global"}

    for p in params:
        rng = p.get("range") or {}
        is_sel = p["type"] == "select"
        is_tog = p["type"] == "toggle"

        if is_sel:
            lo, hi = 0.0, float(len(option_sets[p["options"]]) - 1)
        elif is_tog:
            lo, hi = 0.0, 1.0
        else:
            lo, hi = float(rng.get("min", 0.0)), float(rng.get("max", 1.0))

        opts = ("kOpt_" + p["options"]) if is_sel else "nullptr"
        n_opts = len(option_sets[p["options"]]) if is_sel else 0

        a("    { 0x%04X, %-26s %-22s %-26s %-12s %-15s %-18s %-9s %-9s %-7s %-9s %-9s %-9s %-6s %-22s %2d, %2d }," % (
            p["id"],
            cpp_str(p["key"]) + ",",
            cpp_str(p["juce_id"]) + ",",
            cpp_str(p["name"]) + ",",
            cpp_str(p.get("label", "")) + ",",
            widget_of(p) + ",",
            scope_map.get(p.get("scope", "patch"), "Scope::Patch") + ",",
            curve_map.get(rng.get("curve", "lin"), "Curve::Lin") + ",",
            cpp_float(lo) + ",",
            cpp_float(hi) + ",",
            cpp_float(rng.get("mid", 0.0)) + ",",
            cpp_float(p.get("default", 0)) + ",",
            cpp_str(p.get("unit", "")) + ",",
            ("true," if p.get("bipolar_display") else "false,"),
            opts + ",",
            n_opts,
            p["ui"]["section"],
        ))
    a("};")
    a("")

    # --- section names ------------------------------------------------------
    a(f"static constexpr int kNumSections = {len(sections)};")
    a("static constexpr const char* kSectionNames[kNumSections] = {")
    for s in sections:
        a(f"    {cpp_str(s['name'])},")
    a("};")
    a("")
    a("} // namespace JtParams")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    import sys
    sys.path.insert(0, os.path.join(os.path.dirname(__file__)))
    from gen_params import build_model          # reuse the validated model
    doc = build_model()
    out = emit_juce(doc)
    os.makedirs(os.path.dirname(JUCE_PATH), exist_ok=True)
    with open(JUCE_PATH, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(out)
    print(f"{JUCE_PATH}: {len(doc['params'])} parameters, "
          f"{len(out.splitlines())} lines")
